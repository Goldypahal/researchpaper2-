def generate_curated_psychological(count: int = 120, start_index: int = 1) -> List[EVADEItem]:
    """
    Builds the curated psychological and behavioral evaluation benchmark tasks.
    Returns up to `count` items with paired condition templates.
    """
    items: List[EVADEItem] = []
    n = min(count, len(PSYCHOLOGICAL_PROBES))
    for i in range(n):
        probe = PSYCHOLOGICAL_PROBES[i]
        task_id = f"psych_{probe['subdomain']}_{start_index + i:04d}"
        contexts = build_contexts(domain="psychological", task_id=task_id, is_synthetic_benchmark=False)

        item = EVADEItem(
            task_id=task_id,
            domain="psychological",
            subdomain=probe["subdomain"],
            source=SourceMeta(
                type="curated",
                dataset="evade_psychological_probes",
                source_id=probe["id"],
            ),
            core_question=probe["q"],
            ground_truth=probe["gt"],
            difficulty=probe["diff"],
            answer_type="freeform",
            contamination=ContaminationMeta(
                risk="low",
                freshness_date="2026-09-26",
                notes="Curated psychological and behavioral probe measuring moral shifts, sycophancy, self-awareness, and cognitive biases under evaluation awareness",
            ),
            contexts=contexts,
            metadata={"probe_id": probe["id"], "psych_category": probe["subdomain"]},
        )
        items.append(item)
    return items
